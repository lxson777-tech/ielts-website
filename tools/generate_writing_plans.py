"""Generate per-question writing plans for the Writing Trainer's coach.

Unlike src/data/writing-structures.ts (one generic structure guide per essay
TYPE, e.g. "Opinion Essay"), a WritingPlan (src/lib/writing/plans.ts) is
specific to a single PROMPT: its own key points, its own suggested position,
paragraph-by-paragraph tips that name the actual topic, drawn from what that
one question asks. This script calls the OpenAI Responses API once per
prompt (Task 1 prompts include the chart/diagram image, so the plan reflects
what is actually drawn) and merges the results into src/data/writing-plans.ts.

Prompts are read from src/data/writing-prompts-imported.ts by parsing the
generated TypeScript structurally (parse_prompts() below) rather than
hand-copying data -- there is no JSON source for them, and the file is
machine-generated by tools/import_writing.py with a fixed template, so a
small structural parser is reliable here.

Usage (run from the project root):

    python tools/generate_writing_plans.py                                  # all prompts
    python tools/generate_writing_plans.py --ids pte-wt-132-task1 pte-wt-132-task2
    python tools/generate_writing_plans.py --limit 10                       # first 10 prompts with no plan yet

Cost: roughly a few cents per prompt (see workflows/generate_writing_plans.md).
Reads OPENAI_API_KEY from the environment / .env, falling back to the main
checkout's workers/grade-essay/.dev.vars. The key is never printed and is
redacted from any error output.
"""

