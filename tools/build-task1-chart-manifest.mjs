/* Writes workers/grade-essay/src/task1-charts.ts: the file name and SHA-256
 * of every Task 1 chart in public/pics/writing/imported.
 *
 *   node tools/build-task1-chart-manifest.mjs
 *
 * The essay grader attaches a Task 1 question's chart to the model only when
 * the picture is byte for byte one of these files (see
 * workers/grade-essay/src/task1-visual.ts), so a browser can never make the
 * grader look at, or fetch, anything else. Re-run this after
 * tools/import_writing.py adds or replaces a chart, then redeploy the grader;
 * tests/task1-visual.test.ts fails by name until the list matches the folder.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const CHART_DIR = resolve(REPO, 'public/pics/writing/imported');
const OUT = resolve(REPO, 'workers/grade-essay/src/task1-charts.ts');
const CHART_FILE = /^[A-Za-z0-9._-]+\.(png|jpe?g|webp|gif)$/i;

/** { file name: sha256 hex } for every chart image in the folder, sorted. */
export function chartHashes(dir = CHART_DIR) {
  const out = {};
  for (const name of readdirSync(dir).filter((n) => CHART_FILE.test(n)).sort()) {
    out[name] = createHash('sha256').update(readFileSync(resolve(dir, name))).digest('hex');
  }
  return out;
}

export function manifestSource(hashes) {
  const lines = Object.entries(hashes).map(([name, hash]) => `  '${name}': '${hash}',`);
  return `/* Generated by tools/build-task1-chart-manifest.mjs from
   public/pics/writing/imported. Do not edit by hand: re-run the tool.

   The essay grader attaches a Task 1 chart to the model only when its bytes
   hash to one of these values (see ./task1-visual.ts). */

export const TASK1_CHARTS: Readonly<Record<string, string>> = {
${lines.join('\n')}
};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const hashes = chartHashes();
  writeFileSync(OUT, manifestSource(hashes));
  console.log(`wrote ${Object.keys(hashes).length} charts to ${OUT.replace(REPO, '.')}`);
}
